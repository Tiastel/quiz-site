/**
 * Main option analyzer: Returns a refined 1~2 line concept explanation for any option in a question.
 * Replaces generic placeholders with real, informative domain explanations and natural Korean postpositions.
 */
export function getOptionExplanation(question: Question, optionIndex: number): string {
  const isCorrect = optionIndex === question.correctIndex;
  const rawOpt = question.options[optionIndex] || '';
  const cleanOpt = rawOpt
    .replace(/^([①-⑩0-9A-D가-힣][.)]|\([①-⑩0-9A-D가-힣]\))\s*/i, '')
    .trim();
  const correctName = question.options[question.correctIndex]
    ?.replace(/^([①-⑩0-9A-D가-힣][.)]|\([①-⑩0-9A-D가-힣]\))\s*/i, '')
    .replace(/\s*\([^)]*\)\s*$/, '')
    .trim() || '정답';

  // Case 1: Correct option
  if (isCorrect) {
    const rawExplanation = question.explanation.trim();
    const formatted = formatNaturalKorean(rawExplanation);
    return `정답입니다. ${formatted}`;
  }

  // Case 2: Pre-defined specific wrongOptionsReason exists and is meaningful
  const existingReason = question.wrongOptionsReason?.[optionIndex];
  if (
    existingReason &&
    existingReason.trim().length > 10 &&
    !existingReason.includes('문제의 핵심 조건과 부합하지 않습니다') &&
    !existingReason.includes('오답 선지입니다.')
  ) {
    return formatNaturalKorean(existingReason);
  }

  // Case 3: Look up distractor in knowledge dictionary (Comprehensive, Domain, Curated, Bank)
  const conceptDef = lookupConceptDefinition(cleanOpt, question.topic);
  if (conceptDef) {
    const cleanWord = cleanOpt.replace(/\s*\([^)]*\)\s*$/, '').trim();
    let defSentence = conceptDef;
    if (!conceptDef.startsWith(cleanWord) && !conceptDef.startsWith(`'${cleanWord}'`)) {
      const withJosa = attachJosa(cleanWord, '은/는');
      defSentence = `${withJosa} ${conceptDef}`;
    }

    // Append clear contrast with the question's correct answer if not already contrasting
    if (!defSentence.includes('정답') && !defSentence.includes('구별됩니다') && !defSentence.includes('대비됩니다') && !defSentence.includes('상이합니다')) {
      const contrastJosa = attachJosa(correctName, '과/와');
      defSentence = `${defSentence} 본 문제의 정답 요건인 '${correctName}'${contrastJosa === `${correctName}과` ? '과' : '와'} 구별됩니다.`;
    }

    return formatNaturalKorean(defSentence);
  }

  // Case 4: Long descriptive distractor (e.g. procedural / scenario questions)
  if (cleanOpt.length >= 25 || cleanOpt.includes(' 때문') || cleanOpt.endsWith('다') || cleanOpt.endsWith('음')) {
    const contrastJosa = attachJosa(correctName, '과/와');
    return formatNaturalKorean(
      `오답 서술입니다. 해당 설명은 본 문항의 정답인 '${correctName}'${contrastJosa === `${correctName}과` ? '과' : '와'} 상반되거나, 다른 조건 및 원리를 혼동하도록 유도한 선택지입니다.`
    );
  }

  // Case 5: Numeric, date, or quantitative distractor
  const hasNumbers = /[0-9]{2,}|[0-9]+[억만천원달러km/s초년%]/.test(cleanOpt);
  if (hasNumbers) {
    return formatNaturalKorean(
      `오답 수치입니다. 본 문항의 사실관계 및 학술적 기준값(정답: ${correctName})과 차이가 있는 선택지입니다.`
    );
  }

  // Case 6: Fallback for any other short term: synthesize an authentic morphological definition
  const synthesizedDef = synthesizeMorphologicalConcept(cleanOpt, question.topic);
  const contrastJosa = attachJosa(correctName, '과/와');
  return formatNaturalKorean(
    `${synthesizedDef} 본 문제의 정답 요건인 '${correctName}'${contrastJosa === `${correctName}과` ? '과' : '와'} 구별됩니다.`
  );
}


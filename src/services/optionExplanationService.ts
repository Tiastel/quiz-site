// Find a definition for any distractor option concept
export function lookupConceptDefinition(optionText: string, _topic?: string): string | null {
  const cleanOpt = optionText
    .replace(/^([①-⑩0-9A-D가-힣][.)]|\([①-⑩0-9A-D가-힣]\))\s*/i, '')
    .replace(/\s*\([^)]*\)\s*$/, '')
    .trim();

  const parenMatch = optionText.match(/\(([^)]+)\)/);
  const parenText = parenMatch ? parenMatch[1].trim() : '';

  // 1. Direct exact matches in all dictionaries (O(1) lookups)
  const candidates = [cleanOpt, parenText].filter(Boolean);
  for (const c of candidates) {
    if (ALL_DOMAIN_DICTIONARIES[c]) return ALL_DOMAIN_DICTIONARIES[c];
    if (CONCEPT_EXPLANATIONS[c]) return CONCEPT_EXPLANATIONS[c];
    if (ACADEMIC_DICTIONARY[c]) return ACADEMIC_DICTIONARY[c];
  }

  // Common acronym aliases
  if (cleanOpt === 'CNN' && (CONCEPT_EXPLANATIONS['합성곱 신경망'] || ALL_DOMAIN_DICTIONARIES['합성곱 신경망'])) {
    return CONCEPT_EXPLANATIONS['합성곱 신경망'] || ALL_DOMAIN_DICTIONARIES['합성곱 신경망'];
  }
  if (cleanOpt === 'RNN' && (CONCEPT_EXPLANATIONS['순환 신경망'] || ALL_DOMAIN_DICTIONARIES['순환 신경망'])) {
    return CONCEPT_EXPLANATIONS['순환 신경망'] || ALL_DOMAIN_DICTIONARIES['순환 신경망'];
  }

  // 2. Substring match in all domain dictionaries (require key length >= 3)
  for (const c of candidates) {
    if (c.length >= 3) {
      for (const [key, def] of Object.entries(ALL_DOMAIN_DICTIONARIES)) {
        if (key.length >= 3 && (c.includes(key) || (c.length >= 4 && key.includes(c)))) {
          return def;
        }
      }
      for (const [key, def] of Object.entries(CONCEPT_EXPLANATIONS)) {
        if (key.length >= 3 && (c.includes(key) || (c.length >= 4 && key.includes(c)))) {
          return def;
        }
      }
      for (const [key, def] of Object.entries(ACADEMIC_DICTIONARY)) {
        if (key.length >= 3 && (c.includes(key) || (c.length >= 4 && key.includes(c)))) {
          return def;
        }
      }
    }
  }

  return null;
}

